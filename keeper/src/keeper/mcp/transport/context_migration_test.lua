local test = require("test")
local sql = require("sql")
local funcs = require("funcs")
local uuid = require("uuid")

local DB = "app:mcp_migration_db"
local function migrate(number, id, direction)
    local result, err = funcs.new():call("keeper.mcp.migrations:migration_" .. number, {
        database_id = DB, direction = direction or "up", id = id or uuid.v4(),
    })
    test.is_nil(err)
    test.not_nil(result)
    test.eq(result.status, "complete", tostring(result.error))
end

local function define_tests()
    describe("MCP session context migration", function()
        it("preserves legacy rows without assigning them to a transport session and reruns safely", function()
            for _, number in ipairs({ "01", "02", "03", "04", "05", "06" }) do migrate(number) end
            local db = assert(sql.get(DB))
            local _, token_err = db:execute([[INSERT INTO keeper_mcp_tokens
                (token, label, identity, scopes, created_at, expires_at, revoked, issued_by)
                VALUES ('credential-digest', 'existing-token', 'subject', '["state.read"]', 100, 999, 0, 'issuer')]])
            test.is_nil(token_err)
            local _, err = db:execute([[INSERT INTO keeper_mcp_session_state
                (token, active_traits, overlay_branch, changeset_id, updated_at)
                VALUES ('credential-digest', '["trait-a"]', 'legacy-branch', 'legacy-changeset', 123)]])
            test.is_nil(err)
            db:release()
            migrate("07")
            db = assert(sql.get(DB))
            local rows, query_err = db:query("SELECT * FROM keeper_mcp_session_state")
            test.is_nil(query_err)
            test.eq(#rows, 1)
            test.eq(rows[1].token, "credential-digest")
            test.eq(rows[1].session_id, "")
            test.eq(rows[1].active_traits, '["trait-a"]')
            test.eq(rows[1].overlay_branch, "legacy-branch")
            test.eq(rows[1].changeset_id, "legacy-changeset")
            test.eq(tonumber(rows[1].updated_at), 123)
            local _, insert_err = db:execute([[INSERT INTO keeper_mcp_session_state
                (token, session_id, overlay_branch, changeset_id, updated_at)
                VALUES ('credential-digest', 'transport-session', 'session-branch', 'session-changeset', 456)]])
            test.is_nil(insert_err)
            db:release()
            migrate("07")
            migrate("07", nil, "down")
            db = assert(sql.get(DB))
            rows, query_err = db:query("SELECT * FROM keeper_mcp_session_state ORDER BY session_id")
            test.is_nil(query_err)
            test.eq(#rows, 2)
            test.eq(rows[1].overlay_branch, "legacy-branch")
            test.eq(rows[1].changeset_id, "legacy-changeset")
            test.eq(rows[1].active_traits, '["trait-a"]')
            test.eq(rows[2].overlay_branch, "session-branch")
            test.eq(rows[2].changeset_id, "session-changeset")
            test.eq(tonumber(rows[2].updated_at), 456)
            local credentials, credential_err = db:query("SELECT * FROM keeper_mcp_tokens")
            test.is_nil(credential_err)
            test.eq(#credentials, 1)
            test.eq(credentials[1].token, "credential-digest")
            test.eq(credentials[1].label, "existing-token")
            test.eq(credentials[1].identity, "subject")
            test.eq(credentials[1].scopes, '["state.read"]')
            test.eq(tonumber(credentials[1].created_at), 100)
            test.eq(tonumber(credentials[1].expires_at), 999)
            test.eq(tonumber(credentials[1].revoked), 0)
            test.eq(credentials[1].issued_by, "issuer")
            db:release()
        end)
    end)
end
return { run = test.run_cases(define_tests) }
